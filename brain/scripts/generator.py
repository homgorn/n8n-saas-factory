def generate_project(analysis: dict, output_dir: Path) -> dict:
    """Generate a SaaS project from analysis + template."""
    if not TEMPLATE_DIR.exists():
        raise FileNotFoundError(f"Template not found: {TEMPLATE_DIR}")

    project_name = slugify(analysis["name"])
    output_dir = output_dir / project_name
    output_dir.mkdir(parents=True, exist_ok=True)

    # Copy template (excluding node_modules, .next, .git)
    ignore = shutil.ignore_patterns("node_modules", ".next", ".git", "*.log")
    shutil.copytree(TEMPLATE_DIR, output_dir, dirs_exist_ok=True, ignore=ignore)

    # Generate files
    (output_dir / "src" / "types" / "generated.ts").parent.mkdir(parents=True, exist_ok=True)
    (output_dir / "src" / "types" / "generated.ts").write_text(
        generate_typescript_types(analysis), encoding="utf-8"
    )

    (output_dir / ".env.example").write_text(
        generate_env_example(analysis), encoding="utf-8"
    )

    (output_dir / "README.md").write_text(
        generate_readme(analysis, project_name), encoding="utf-8"
    )

    # Replace placeholders in all text files
    placeholders = {
        "{{PROJECT_NAME}}": project_name,
        "{{WORKFLOW_NAME}}": analysis["name"],
        "{{WORKFLOW_ID}}": analysis["workflow_id"],
        "{{TRIGGER_TYPE}}": analysis["trigger_type"],
        "{{COMPLEXITY}}": str(analysis["complexity_score"]),
        "{{NODE_COUNT}}": str(analysis["node_count"]),
        "{{AGENT_COUNT}}": str(len(analysis["ai_agents"])),
    }

    for path in output_dir.rglob("*"):
        if path.is_file() and path.suffix in (".ts", ".tsx", ".js", ".json", ".md", ".sql", ".env", ".example"):
            try:
                content = path.read_text(encoding="utf-8")
                for placeholder, value in placeholders.items():
                    content = content.replace(placeholder, value)
                path.write_text(content, encoding="utf-8")
            except (UnicodeDecodeError, PermissionError):
                pass

    return {
        "project_name": project_name,
        "output_dir": str(output_dir),
        "workflow": analysis["name"],
        "files_generated": len(list(output_dir.rglob("*"))),
    }


def main() -> None:
    ap = argparse.ArgumentParser(description="Generate SaaS from workflow analysis")
    ap.add_argument("analysis", nargs="?", help="path to analysis JSON")
    ap.add_argument("--from-workflow", help="path to workflow JSON (runs analyzer first)")
    ap.add_argument("--all", action="store_true", help="generate for all workflows")
    ap.add_argument("-o", "--output", required=True, help="output directory")
    args = ap.parse_args()

    output_dir = Path(args.output)
    output_dir.mkdir(parents=True, exist_ok=True)

    if args.all:
        import subprocess
        # Run analyzer first
        analyses_dir = ROOT / "brain" / "research" / "workflow-analyses"
        if not analyses_dir.exists():
            print("Running analyzer first...")
            subprocess.run([sys.executable, str(ANALYZER), "--all"], check=True)

        results = []
        for analysis_path in sorted(analyses_dir.glob("*.json")):
            if analysis_path.name.startswith("_"):
                continue
            analysis = json.loads(analysis_path.read_text(encoding="utf-8"))
            result = generate_project(analysis, output_dir)
            results.append(result)
            print(f"  generated {result['project_name']} ({result['files_generated']} files)")

        print(f"\n  {len(results)} projects generated -> {output_dir}")
        return

    if args.from_workflow:
        import subprocess
        # Run analyzer on the workflow
        tmp = output_dir / ".tmp-analysis.json"
        subprocess.run(
            [sys.executable, str(ANALYZER), args.from_workflow, "--out", str(tmp)],
            check=True,
        )
        analysis = json.loads(tmp.read_text(encoding="utf-8"))
        tmp.unlink()
    elif args.analysis:
        analysis = json.loads(Path(args.analysis).read_text(encoding="utf-8"))
    else:
        ap.error("provide an analysis JSON, --from-workflow, or --all")

    result = generate_project(analysis, output_dir)
    print(f"Generated: {result['project_name']}")
    print(f"  Output: {result['output_dir']}")
    print(f"  Files: {result['files_generated']}")
    print(f"\nNext steps:")
    print(f"  cd {result['output_dir']}")
    print(f"  npm install")
    print(f"  cp .env.example .env  # fill in values")
    print(f"  npm run dev")


if __name__ == "__main__":
    main()