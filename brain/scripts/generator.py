        "NEXT_PUBLIC_CLERK_PUBLISHABLE_KEY=",
        "CLERK_SECRET_KEY=",
        "",
        "# --- Database (Supabase) ---",
        "NEXT_PUBLIC_SUPABASE_URL=",
        "NEXT_PUBLIC_SUPABASE_ANON_KEY=",
        "SUPABASE_SERVICE_ROLE_KEY=",
        "",
        "# --- Billing (Stripe) ---",
        "STRIPE_SECRET_KEY=",
        "STRIPE_WEBHOOK_SECRET=",
        "NEXT_PUBLIC_STRIPE_PUBLISHABLE_KEY=",
        "STRIPE_PRICE_ID=",
