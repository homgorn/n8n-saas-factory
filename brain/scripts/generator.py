#!/usr/bin/env python3
"""
generator.py — Workflow-to-SaaS generator (F005).

Reads a workflow analysis JSON (produced by analyzer.py) and generates a complete
SaaS project from the ai-tool template, with placeholders replaced, types generated,
and deployment instructions.

Usage:
    python brain/scripts/generator.py <analysis.json> -o ./generated-saas/my-saas
    python brain/scripts/generator.py --from-workflow <workflow.json> -o ./generated-saas/my-saas
    python brain/scripts/generator.py --all -o ./generated-saas  # all 12 workflows

The generator is pure file I/O + string replacement. No API keys, no network.
"""

from __future__ import annotations

import argparse
import json
import re
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
TEMPLATE_DIR = ROOT / "saas-factory" / "templates" / "ai-tool"
ANALYZER = ROOT / "brain" / "scripts" / "analyzer.py"


def slugify(name: str) -> str:
    name = re.sub(r"[^\w\s-]", "", name.lower())
    return re.sub(r"[\s_]+", "-", name).strip("-")[:60] or "saas"


