def topic_of(path: Path) -> str:
    try:
        return path.relative_to(SOURCE).parts[0]
    except (ValueError, IndexError):
        return "other"


def iter_source_docs() -> list[Path]:
    """Every markdown page under the docs tree.

    `_workflows/` holds the runnable example JSON used by the tutorials and is worth indexing.
    GitBook internals (`.gitbook/`, `includes/`) are not content and are skipped.
    """
    if not SOURCE.exists():
        sys.exit(f"source docs not found: {SOURCE}")
    out = []
    for p in SOURCE.rglob("*.md"):
        parts = p.relative_to(SOURCE).parts
        if ".gitbook" in parts:
            continue
        if "includes" in parts:
            continue
        if p.name in {"README.md"} and len(parts) == 1:
            continue
        out.append(p)
    return sorted(out)


def build() -> dict:
    started = datetime.now(timezone.utc)
    conn = db_connect(recreate=True)
    SCHEMA_PATH.parent.mkdir(parents=True, exist_ok=True)
    SCHEMA_PATH.write_text(SCHEMA + "\n" + FTS_SCHEMA, encoding="utf-8")

    files = iter_source_docs()
    if not files:
        sys.exit("no markdown files discovered")

    by_topic: dict[str, list[dict]] = defaultdict(list)
    entities: dict[tuple[str, str], dict] = {}
    triples: list[dict] = []
    seen_hashes: dict[str, str] = {}
    written = 0
    total_chunks = 0

    for path in files:
        raw = path.read_text(encoding="utf-8", errors="replace")
        fm, body = parse_frontmatter(raw)
        rel = path.relative_to(SOURCE).as_posix()
        topic = topic_of(path)
        slug = slugify(path.stem)
        doc_id = hashlib.sha1(rel.encode()).hexdigest()[:12]
        content_hash = hashlib.sha256(raw.encode()).hexdigest()

        clean = Stripper.clean(body)
        title = stringify(fm.get("title") or path.stem.replace("-", " ").replace("_", " ").title())
        summary = summarise(clean, title)
        headings = [h for _, h in extract_headings(clean)]
        difficulty = difficulty_of(path, fm)
        source_url = f"https://docs.n8n.io/{rel[:-3] if rel.endswith('.md') else rel}"

        record = {
            "doc_id": doc_id,
            "slug": slug,
            "title": title,
            "topic": topic,
            "rel_path": rel,
            "source_url": source_url,
            "summary": summary,
            "difficulty": difficulty,
            "content_type": stringify(fm.get("contentType", "reference")),
            "content_hash": content_hash,
            "bytes": len(raw),
            "words": len(clean.split()),
            "headings": headings,
            "body": clean,
            "frontmatter": fm,
        }

        chunks = chunk_document(clean, doc_id)
        record["chunk_count"] = len(chunks)
        total_chunks += len(chunks)
        by_topic[topic].append(record)
        seen_hashes[content_hash] = doc_id
        written += 1

        # ---- entities ----------------------------------------------------
        for family, node in set(NODE_RE.findall(raw)):
            node_name = f"n8n-nodes-{family}.{node}"
            key = (node_name, "node")
            entities.setdefault(key, {"name": node_name, "kind": "node", "topic": topic, "mentions": 0})["mentions"] += 1
            triples.append({
                "subject": record["slug"],
                "predicate": "documents_node",
                "object": node_name,
                "source": record["source_url"],
            })
        for env in set(ENV_RE.findall(raw)):
            if env.startswith("N8N_") or env in {"WEBHOOK_URL", "EXECUTIONS_DATA", "NODE_OPTIONS"}:
                entities.setdefault((env, "env_var"), {"name": env, "kind": "env_var", "topic": topic, "mentions": 0})["mentions"] += 1
                triples.append({
                    "subject": record["slug"],
                    "predicate": "sets_env_var",
                    "object": env,
                    "source": record["source_url"],
                })
        for ident in set(CODE_RE.findall(raw)):
            if ident.startswith("n8n-nodes-"):
                continue
            if len(ident) > 2 and not ident.startswith("$"):
                entities.setdefault((ident, "identifier"), {"name": ident, "kind": "identifier", "topic": topic, "mentions": 0})["mentions"] += 1
        for link in sorted(set(LINK_RE.findall(raw)))[:20]:
            triples.append({
                "subject": record["slug"],
                "predicate": "links_to",
                "object": link,
                "source": record["source_url"],
            })

        # ---- runnable workflow JSON -------------------------------------
        # docs/_workflows/*.json are complete, importable n8n workflows. They are the best
        # available corpus for the workflow analyser, so index them alongside the prose.
        if path.suffix == ".json" or rel.startswith("_workflows/"):
            pass  # handled by the separate pass below

        # ---- persist doc -------------------------------------------------
        now = started.isoformat()
        conn.execute(
            """INSERT OR REPLACE INTO docs
               (doc_id, slug, title, topic, source_path, source_url, summary, difficulty,
                content_type, content_hash, bytes, words, chunk_count, fetched_at, updated_at)
               VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?,?,?)""",
            (doc_id, slug, title, topic, str(path), source_url, summary, difficulty,
             record["content_type"], content_hash, len(raw), record["words"], len(chunks), now, now),
        )
        conn.execute("DELETE FROM chunks WHERE doc_id = ?", (doc_id,))
        conn.executemany(
            "INSERT OR REPLACE INTO chunks (chunk_id, doc_id, ordinal, heading, kind, text, tokens) VALUES (?,?,?,?,?,?,?)",
            [(c["chunk_id"], doc_id, c["ordinal"], c["heading"], c["kind"], c["text"], c["tokens"]) for c in chunks],
        )

    # Claims survive a rebuild. They are authored, not derived: forge.py recreates the
    # database from scratch, so anything asserted by a human must be re-applied from a file
    # that lives in git. brain/index/claims.json is that file; seed_claims.py writes it.
    claims_file = INDEX / "claims.json"
    if claims_file.exists():
        payload = json.loads(claims_file.read_text(encoding="utf-8"))
        now_iso = started.isoformat()
        for claim in payload.get("claims", []):
            conn.execute(
                """INSERT OR REPLACE INTO claims (id, text, kind, source, observed_at, doc_id)
                   VALUES (?,?,?,?,?,?)""",
                (claim["id"], claim["text"], claim["type"],
                 claim.get("source"), claim.get("observed_at"), claim.get("doc_id")),
            )
        print(f"  re-applied {len(payload.get('claims', []))} claims from {claims_file.name}")

    # ---- runnable workflow corpus -------------------------------------
    wf_count, wf_stats = index_workflows(conn, started)

    # ---- entities and triples ------------------------------------------
    for (name, kind), meta in entities.items():
        conn.execute(
            "INSERT OR REPLACE INTO entities (name, kind, topic, first_seen, mentions) VALUES (?,?,?,?,?)",
            (name, kind, meta["topic"], started.isoformat(), meta["mentions"]),
        )
    conn.executemany(
        "INSERT OR IGNORE INTO triples (subject, predicate, object, source) VALUES (?,?,?,?)",
        [(t["subject"], t["predicate"], t["object"], t["source"]) for t in triples],
    )

    # ---- FTS ------------------------------------------------------------
    try:
        conn.execute("DELETE FROM docs_fts")
        for topic, records in by_topic.items():
            for r in records:
                conn.execute(
                    "INSERT INTO docs_fts (slug, title, summary, headings, content) VALUES (?,?,?,?,?)",
                    (r["slug"], r["title"], r["summary"], " | ".join(r["headings"]), r["body"]),
                )
    except sqlite3.OperationalError as exc:
        print(f"  ! fts unavailable: {exc}")

    conn.execute(
        "INSERT INTO run_log (ran_at, command, docs_seen, docs_written, docs_removed, chunks, entities, triples, notes) VALUES (?,?,?,?,?,?,?,?,?)",
        (started.isoformat(), "build", len(files), written, 0, total_chunks, len(entities), len(triples),
         "full rebuild"),
    )
    conn.commit()

    # ---- markdown output -------------------------------------------------
    write_markdown(by_topic)

    conn.close()
    return {
        "files": len(files),
        "docs": written,
        "chunks": total_chunks,
        "entities": len(entities),
        "triples": len(triples),
        "topics": len(by_topic),
        "words": sum(r["words"] for recs in by_topic.values() for r in recs),
        "workflows": wf_count,
        "wf_top_nodes": wf_stats,
    }


def index_workflows(conn: sqlite3.Connection, started: datetime) -> tuple[int, dict]:
    """Index the importable workflow JSON under docs/_workflows.

    These are complete n8n workflows — the highest-value corpus in the repo, because the
    SaaS generator needs real trigger/node/credential shapes rather than prose about them.
    """
    wf_dir = SOURCE / "_workflows"
    if not wf_dir.exists():
        return 0, {}

    conn.execute("""
        CREATE TABLE IF NOT EXISTS workflows (
            slug        TEXT PRIMARY KEY,
            name        TEXT NOT NULL,
            node_count  INTEGER NOT NULL,
            node_types  TEXT NOT NULL,
            trigger_type TEXT,
            credentials TEXT NOT NULL,
            source_path TEXT NOT NULL,
            raw         TEXT NOT NULL,
            fetched_at  TEXT NOT NULL
        )
    """)

    count = 0
    types: Counter = Counter()
    for path in sorted(wf_dir.rglob("*.json")):
        try:
            wf = json.loads(path.read_text(encoding="utf-8"))
        except json.JSONDecodeError:
            continue
        if not isinstance(wf, dict) or "nodes" not in wf:
            continue

        nodes = wf.get("nodes") or []
        node_types = [n.get("type", "?") for n in nodes if isinstance(n, dict)]
        creds = sorted({
            c.get("type")
            for n in nodes if isinstance(n, dict)
            for c in (n.get("credentials") or {}).values()
            if isinstance(c, dict) and c.get("type")
        })
        triggers = [t for t in node_types if "trigger" in t.lower() or t.endswith("webhook")]
        name = wf.get("name") or path.stem.replace("_", " ")
        slug = slugify(path.stem)

        conn.execute(
            """INSERT OR REPLACE INTO workflows
               (slug, name, node_count, node_types, trigger_type, credentials, source_path, raw, fetched_at)
               VALUES (?,?,?,?,?,?,?,?,?)""",
            (
                slug, name, len(nodes), json.dumps(node_types),
                triggers[0] if triggers else None,
                json.dumps(creds), str(path),
                json.dumps(wf, ensure_ascii=False), started.isoformat(),
            ),
        )
        types.update(node_types)
        count += 1

    conn.commit()
    return count, dict(types.most_common(20))


