# chunking
# --------------------------------------------------------------------------

def chunk_document(body: str, doc_id: str) -> list[dict]:
    """Split on H2 boundaries; code fences and tables stay whole inside a chunk."""
    lines = body.splitlines()
    sections: list[tuple[str, list[str]]] = []
    heading = "(intro)"
    buffer: list[str] = []

    in_fence = False
    for line in lines:
        if re.match(r"^\s*(```|~~~)", line):
            in_fence = not in_fence
        if not in_fence:
            m = re.match(r"^(#{1,3})\s+(.*)$", line)
            if m:
                if buffer and any(b.strip() for b in buffer):
                    sections.append((heading, buffer))
                heading = m.group(2).strip()
                buffer = [line]
                continue
        buffer.append(line)
    if buffer and any(b.strip() for b in buffer):
        sections.append((heading, buffer))

    chunks: list[dict] = []
    ordinal = 0
    for heading, section_lines in sections:
        text = "\n".join(section_lines).strip()
        if not text:
            continue
        text = re.sub(r"^#{1,6}\s+.*$", "", text, count=1).strip()
        if not text:
            continue
        kind = "prose"
        if re.search(r"^\s*(```|~~~)", "\n".join(section_lines), re.M):
            kind = "code_example"
        elif "|" in text and re.search(r"^\s*\|.*\|", text, re.M):
            kind = "table"
        if re.search(r"(?i)\b(warning|caution|deprecated|do not)\b", text[:400]):
            kind = "warning"
        elif re.search(r"(?i)\b(tip|note|hint)\b", text[:400]):
            kind = "tip"

        # split anything enormous so an embedding never truncates silently
        if len(text) > 6000:
            for i in range(0, len(text), 6000):
                piece = text[i : i + 6000]
                chunks.append({
                    "chunk_id": f"{doc_id}#{ordinal:03d}",
                    "ordinal": ordinal,
                    "heading": heading,
                    "kind": kind,
                    "text": piece,
                    "tokens": len(piece) // 4,
                })
                ordinal += 1
            continue

        chunks.append({
            "chunk_id": f"{doc_id}#{ordinal:03d}",
            "ordinal": ordinal,
            "heading": heading,
            "kind": kind,
            "text": text,
            "tokens": len(text) // 4,
        })
        ordinal += 1
    return chunks


