class Stripper:
    """Removes GitBook directives, HTML blobs and MDX so the body reads as prose."""

    # {% hint style="info" %} ... {% /hint %}  and  {% @block content="..." %}
    DIRECTIVE_OPEN = re.compile(r"\{%-?\s*(?:hint|/hint|@[\w.-]+|[\w-]+)[^%}]*-?%\}", re.I)
    # :::info Title ... :::   (colon fences)
    COLON_FENCE = re.compile(r"^:::\s*\w+.*$", re.M)
    # <figure>...</figure>, <details>...</details>, <table>...</table>
    HTML_BLOCK = re.compile(
        r"<(figure|details|table|summary|img|picture|source|div)\b[^>]*>.*?</\1>", re.I | re.S
    )
    SELF_CLOSING = re.compile(r"<(img|source|br|hr|input)\b[^>]*/?>", re.I)
    # -8<-- "path"  include directives
    INCLUDE = re.compile(r'^\s*-\d+<--\s*".*?".*$', re.M)
    # [[label|target]] internal links
    MDX_LINK = re.compile(r"\[\[([^\]|]+)\|([^\]]+)\]\]")
    # data-mention href="/path"  → path
    DATA_MENTION = re.compile(r'<a\s+data-mention\s+href="([^"]*)"[^>]*>(.*?)</a>', re.S | re.I)
    ANCHOR_ONLY = re.compile(r'<a\s+id="[^"]*"[^>]*>(.*?)</a>', re.S | re.I)
    BARE_TAG = re.compile(r"</?[a-z][a-z0-9]*(\s[^>]*)?>", re.I)
    HTML_COMMENT = re.compile(r"<!--.*?-->", re.S)
    GITBOOK_IMG = re.compile(r"!\[[^\]]*\]\(https://[^)]*gitbook[^)]*\)", re.I)
    # {% @n8n-blocks/... content="%7B%0A..." %} workflow embeds — keep nothing
    N8N_BLOCK = re.compile(r'\{%-?\s*@n8n-blocks/.*?-?%\}', re.S)

    @classmethod
    def clean(cls, text: str) -> str:
        text = cls.N8N_BLOCK.sub("", text)
        text = cls.HTML_COMMENT.sub("", text)
        text = cls.HTML_BLOCK.sub("", text)
        text = cls.INCLUDE.sub("", text)
        text = cls.DIRECTIVE_OPEN.sub("", text)
        text = cls.COLON_FENCE.sub("", text)
        text = cls.MDX_LINK.sub(r"\1 (\2)", text)
        text = cls.DATA_MENTION.sub(r"\2 (\1)", text)
        text = cls.ANCHOR_ONLY.sub(r"\1", text)
        text = cls.SELF_CLOSING.sub("", text)
        text = cls.GITBOOK_IMG.sub("", text)
        text = cls.BARE_TAG.sub("", text)
        # decode the html entities that survive stripping
        for a, b in (
            ("&amp;", "&"), ("&lt;", "<"), ("&gt;", ">"), ("&quot;", '"'),
            ("&#39;", "'"), ("&nbsp;", " "), ("&mdash;", "—"), ("&ndash;", "–"),
        ):
            text = text.replace(a, b)
        # collapse >2 blank lines
        text = re.sub(r"\n{3,}", "\n\n", text)
        # trim trailing spaces per line
        text = re.sub(r"[ \t]+\n", "\n", text)
        return text.strip()


# --------------------------------------------------------------------------
# frontmatter (YAML subset — n8n docs only uses scalars and flat lists)
# --------------------------------------------------------------------------

def parse_frontmatter(raw: str) -> tuple[dict, str]:
    if not raw.startswith("---"):
        return {}, raw
    end = raw.find("\n---", 3)
    if end == -1:
        return {}, raw
    head = raw[3:end].strip()
    body = raw[end + 4 :].lstrip("\n")
    data: dict = {}
    key = None
    for line in head.splitlines():
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        if line.lstrip().startswith("- ") and key:
            data.setdefault(key, [])
            if isinstance(data[key], list):
                data[key].append(line.lstrip()[2:].strip().strip("\"'"))
            continue
        if ":" not in line:
            continue
        key, _, value = line.partition(":")
        key = key.strip()
        value = value.strip()
        if value == "":
            data[key] = []
        elif value.startswith("[") and value.endswith("]"):
            inner = value[1:-1].strip()
            data[key] = [p.strip().strip("\"'") for p in inner.split(",") if p.strip()] if inner else []
        else:
            data[key] = value.strip("\"'")
    return data, body


def stringify(value) -> str:
    if isinstance(value, list):
        return ", ".join(str(v) for v in value)
    if isinstance(value, bool):
        return "yes" if value else "no"
    return str(value)


def yaml_scalar(value) -> str:
    if isinstance(value, list):
        return "[" + ", ".join(yaml_scalar(v) for v in value) + "]"
    if isinstance(value, bool):
        return "true" if value else "false"
    return f'"{str(value).replace(chr(34), "")}"'


# --------------------------------------------------------------------------
# entity extraction
# --------------------------------------------------------------------------

NODE_RE = re.compile(r"\bn8n-nodes-(base|langchain)\.([a-z0-9_]+)\b")
ENV_RE = re.compile(r"\b([A-Z][A-Z0-9]{3,}(?:_[A-Z0-9]+)+)\b")
CODE_RE = re.compile(r"`([A-Za-z_][A-Za-z0-9_.]*)`")
HEADING_RE = re.compile(r"^(#{1,6})\s+(.*)$", re.M)
LINK_RE = re.compile(r"\[[^\]]+\]\((/[^)\s]+)\)")


def slugify(text: str) -> str:
    text = re.sub(r"[^\w\s-]", "", text.lower())
    return re.sub(r"[\s_]+", "-", text).strip("-")[:80] or "untitled"


def summarise(body: str, title: str) -> str:
    """First meaningful prose sentence, capped. Must stand alone without the page."""
    for block in re.split(r"\n\s*\n", Stripper.clean(body)):
        block = block.strip()
        if not block or block.startswith(("#", "|", "```", "-", "*", ">", "{", "!", "[")):
            continue
        block = re.sub(r"\s+", " ", block)
        if len(block) < 40:
            continue
        sentence = re.split(r"(?<=[.!?])\s", block)[0].strip()
        if len(sentence) > MAX_SUMMARY:
            cut = sentence[:MAX_SUMMARY].rsplit(" ", 1)[0]
            sentence = cut.rstrip(",;:") + "…"
        return sentence
    # prose was empty — fall back to the first heading, stated plainly
    heading = title.strip() or "Documentation page"
    return f"{heading} — reference page with limited prose."


def extract_headings(body: str) -> list[tuple[int, str]]:
    return [(len(m.group(1)), m.group(2).strip()) for m in HEADING_RE.finditer(body)]


def difficulty_of(path: Path, fm: dict) -> str:
    joined = str(path).lower()
    if any(k in joined for k in ("create-nodes", "api/", "configure-n8n", "scaling", "security/", "reference")):
        return "advanced"
    if any(k in joined for k in ("build-your-first", "get-started", "install-options", "try-it-out")):
        return "beginner"
    return stringify(fm.get("contentType", "reference")) and "intermediate"


