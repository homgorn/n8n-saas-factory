def main() -> None:
    cmd = sys.argv[1] if len(sys.argv) > 1 else "build"
    if cmd == "build":
        result = build()
        print("=== wiki built ===")
        for k, v in result.items():
            print(f"  {k:<10} {v:,}" if isinstance(v, int) else f"  {k:<10} {v}")
        print(f"\n  root       {BRAIN}")
        print(f"  db         {DB_PATH}")
    elif cmd == "stats":
        stats()
    elif cmd == "query":
        query(sys.argv[2])
    elif cmd == "ask":
        ask(" ".join(sys.argv[2:]))
    else:
        sys.exit(f"unknown command {cmd!r}; try build | stats | query | ask")


